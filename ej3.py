def main():
    ancho = 16
    alto = 12.0

    print(type(ancho))
    print(type(alto))

    print(f"el tipo de dato de la expresion ancho / 2 es {type(ancho / 2)}")
    print(f"el tipo de dato de la expresion ancho // 2 es {type(ancho // 2)}")
    print(f"el tipo de dato de la expresion alto / 3 es {type(alto / 3)}")
    print(f"el tipo de dato de la expresion 1 + 2 * 5 es {type(1 + 2 * 5)}")

if __name__ == "__main__":
    main()