def main():
    num1 = float(input("Introduce el 1º numero: "))
    num2 = float(input("Introduce el 2º numero: "))
    num3 = float(input("Introduce el 3º numero: "))
    suma: int = num1 + num2 + num3
    print(f"la suma de los tres numeros es igual a {suma}")
if __name__ == "__main__":
    main()